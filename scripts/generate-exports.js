import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import ts from 'typescript';
import { rootExtraExports, uiEntryPoints } from './ui-entrypoints.mjs';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const componentsDir = path.resolve(__dirname, '../src/components');
const outputFile = path.resolve(__dirname, '../src/index.tsx');
const entriesDir = path.resolve(__dirname, '../src/entries');

// One folder per component (MAIR-608 component tree): `src/components/<Name>/<Name>.tsx`,
// reached through the folder's `index.ts`. Loose helper files beside the folders are not exported.
const files = fs.readdirSync(componentsDir, { withFileTypes: true })
  .filter(entry => entry.isDirectory() && fs.existsSync(path.join(componentsDir, entry.name, `${entry.name}.tsx`)))
  .map(entry => entry.name);
const exports = files.map(name => `export { ${name} } from './components/${name}';`);
fs.writeFileSync(outputFile, [...exports, ...rootExtraExports].join('\n') + '\n', 'utf8');
fs.mkdirSync(entriesDir, { recursive: true });

for (const [name, entry] of Object.entries(uiEntryPoints)) {
  const lines = ["'use client';", '', '// Generated by scripts/generate-exports.js; edit ui-entrypoints.mjs.'];
  for (const component of entry.components) {
    const sourcePath = path.join(componentsDir, component, `${component}.tsx`);
    const source = ts.createSourceFile(sourcePath, fs.readFileSync(sourcePath, 'utf8'), ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
    lines.push(`export { ${component} } from '../components/${component}';`);
    const publicTypes = source.statements.filter(node =>
      (ts.isInterfaceDeclaration(node) || ts.isTypeAliasDeclaration(node)) &&
      ts.getModifiers(node)?.some(modifier => modifier.kind === ts.SyntaxKind.ExportKeyword)
    ).map(node => node.name.text);
    if (publicTypes.length) lines.push(`export type { ${publicTypes.join(', ')} } from '../components/${component}';`);
  }
  for (const typeFile of entry.typeFiles ?? []) {
    fs.accessSync(path.join(componentsDir, typeFile));
    lines.push(`export type * from '../components/${typeFile}';`);
  }
  lines.push(...entry.extra ?? []);
  fs.writeFileSync(path.join(entriesDir, `${name}.ts`), lines.join('\n') + '\n', 'utf8');
}
console.log(`Generated root and ${Object.keys(uiEntryPoints).length} UI module entries from ${files.length} components.`);
