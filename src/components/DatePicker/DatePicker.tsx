'use client';

import React from 'react';
import { Calendar as CalendarIcon } from 'lucide-react';

import type { Size } from '@mairie360/lib-components/theme';
import { Calendar, addDays, formatFullDate, formatShortDate, isDateDisabled, parseIsoDate, toIsoDate, weekdayIndex, type CalendarView, type DateBounds } from '../Calendar';
import { Field, fieldDescriptionIds } from '../Field';
import { componentMarker } from '../component-marker';
import { DateShortcuts, type DateShortcut } from './components/DateShortcuts';
import { DateTrigger, type DateDisplay } from './components/DateTrigger';
import { useDatePopover } from './use-date-popover';

export interface DatePickerProps extends DateBounds, Omit<React.HTMLAttributes<HTMLDivElement>, 'onChange' | 'defaultValue'> {
  label: string;
  hint?: React.ReactNode;
  error?: React.ReactNode;
  required?: boolean;
  disabled?: boolean;
  size?: Size;
  /** Id of the trigger (the label points to it); generated by default. */
  id?: string;
  /** Name of the hidden input carrying the ISO value in a native form. */
  name?: string;
  /** Chosen day, ISO `YYYY-MM-DD` (controlled); null for none. */
  value?: string | null;
  /** Initial day when uncontrolled. */
  defaultValue?: string | null;
  /** Called with the ISO day chosen, or null when cleared. */
  onChange?: (value: string | null) => void;
  placeholder?: string;
  /** View the calendar opens on: `years` for a birth date. */
  startView?: CalendarView;
  /** Shows the shortcuts Aujourd’hui, Demain, Lundi prochain, Dans une semaine (default true). */
  shortcuts?: boolean;
  /** Days carrying events: a dot in the calendar. */
  events?: readonly string[];
  /** `auto`: date in full, short form when the field is narrow. */
  display?: DateDisplay;
}

/** The four shortcuts of DatePicker, from `today` (ISO): Aujourd’hui, Demain, Lundi prochain (always after today), Dans une semaine. */
export function datePickerShortcuts(today: string = toIsoDate(new Date())): DateShortcut[] {
  return [
    { id: 'today', label: 'Aujourd’hui', value: today },
    { id: 'tomorrow', label: 'Demain', value: addDays(today, 1) },
    { id: 'next-monday', label: 'Lundi prochain', value: addDays(today, 7 - weekdayIndex(today)) },
    { id: 'in-a-week', label: 'Dans une semaine', value: addDays(today, 7) },
  ];
}

/**
 * Date field with a calendar (MAIR-1099, Figma `DatePicker`; replaces `DateField`): the date written in full
 * (« jeudi 3 décembre 2026 », « 3 déc. 2026 » when narrow), a popover with shortcuts and Calendar, a clear
 * button, `min` / `max` / `disabledDates`. Value ISO `YYYY-MM-DD`. Échap or a choice closes the popover and
 * gives the focus back to the field.
 */
export function DatePicker({
  label, hint, error, required = false, disabled = false, size = 'm', id, name, value, defaultValue = null, onChange,
  placeholder = 'Choisir une date', startView = 'days', shortcuts = true, events, display = 'auto', min, max, disabledDates, className = '', ...props
}: DatePickerProps) {
  const generated = React.useId();
  const fieldId = id ?? `date-picker-${generated.replace(/:/g, '')}`;
  const popoverId = `${fieldId}-popover`;
  const [inner, setInner] = React.useState<string | null>(defaultValue);
  const current = value !== undefined ? value : inner;
  const chosen = parseIsoDate(current) ? current : null;
  const bounds: DateBounds = { min, max, disabledDates };
  const popover = useDatePopover(disabled);

  const commit = (next: string | null) => {
    if (value === undefined) setInner(next);
    onChange?.(next);
  };
  const pick = (iso: string) => {
    commit(iso);
    popover.close();
  };

  return (
    <Field {...props} {...componentMarker('DatePicker', props)} htmlFor={fieldId} label={label} hint={hint} error={error} required={required} size={size} disabled={disabled} className={className}>
      <div {...popover.wrapperProps} className="relative">
        <DateTrigger
          id={fieldId}
          triggerRef={popover.trigger}
          icon={CalendarIcon}
          name={`${label}${required ? ' (obligatoire)' : ''}, ${chosen ? formatFullDate(chosen) : 'aucune date choisie'}`}
          longText={chosen ? formatFullDate(chosen) : ''}
          shortText={chosen ? formatShortDate(chosen) : ''}
          placeholder={placeholder}
          display={display}
          open={popover.open}
          controls={popoverId}
          disabled={disabled}
          invalid={Boolean(error)}
          required={required}
          describedBy={fieldDescriptionIds(fieldId, hint, error)}
          size={size}
          clearLabel={`Effacer la date « ${label} »`}
          onToggle={popover.toggle}
          onOpen={() => popover.setOpen(true)}
          onClear={() => { commit(null); popover.trigger.current?.focus(); }}
        />
        {name ? <input type="hidden" name={name} value={chosen ?? ''} /> : null}
        {popover.open ? (
          <div
            {...popover.popoverProps}
            id={popoverId}
            role="dialog"
            aria-label={`${label} : choisir une date`}
            className="mairie-popover-in absolute left-0 z-[45] rounded-[var(--mairie-radius-l)] border border-[var(--mairie-border)] bg-[var(--mairie-surface)]"
            style={{ top: 'calc(100% + 6px)', padding: 12, boxShadow: 'var(--mairie-shadow-pop)', maxWidth: 'calc(100vw - 32px)' }}
          >
            {shortcuts ? <DateShortcuts shortcuts={datePickerShortcuts()} value={chosen} isDisabled={iso => isDateDisabled(iso, bounds)} onPick={pick} /> : null}
            <Calendar value={chosen} onChange={pick} autoFocus defaultView={startView} events={events} min={min} max={max} disabledDates={disabledDates} label={`Calendrier : ${label}`} />
          </div>
        ) : null}
      </div>
    </Field>
  );
}
